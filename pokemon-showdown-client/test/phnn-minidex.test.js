		'a computed key': withRow('\t[alert(1)]:{num:1},'),
		'a computed field': withRow('\tbulbasaur:{[alert(1)]:1},'),
		'a __proto__ key': withRow('\t__proto__:{num:1},'),
		'a constructor key': withRow('\tconstructor:{num:1},'),
