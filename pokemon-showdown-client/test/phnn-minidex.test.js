describe('upstream minidex refresh', () => {
	it('reads the resource server the build uses and only accepts a bare host', () => {
		assert.equal(resolveHost(tempRoot('Sprites.Example.test:8443')), 'sprites.example.test:8443');
		assert.equal(resolveHost(tempRoot()), 'play.pokemonshowdown.com');
		for (const bad of ['https://evil.test', 'evil.test/data', 'user@evil.test', 'evil.test\n', 'evil.test?', '', 7]) {
			assert.equal(resolveHost(tempRoot(bad)), 'play.pokemonshowdown.com', JSON.stringify(bad));
		}
	});

	it('refuses to fetch anything but https', async () => {
		let hits = 0;
		const server = http.createServer((req, res) => {
			hits++;
			res.end(fullSize(UPSTREAM_MAIN));
		});
		await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
		try {
			const url = `http://127.0.0.1:${server.address().port}/data/pokedex-mini.js`;
			await assert.rejects(fetchText(url), /non-https/);
			assert.equal(hits, 0);
		} finally {
			server.close();
		}
	});

	it('writes validated copies of both tables and a last good copy', async () => {
		const root = tempRoot('sprites.example.test');
		const { urls, fetchImpl } = serve({ [MAIN.file]: fullSize(UPSTREAM_MAIN), [BW.file]: fullSize(UPSTREAM_BW) });
		const { result, line } = await run(root, fetchImpl);
		assert.equal(result.status, 'fetched');
		assert.deepEqual(urls.sort(), [
			'https://sprites.example.test/data/pokedex-mini-bw.js',
			'https://sprites.example.test/data/pokedex-mini.js',
		]);
		assert.match(line, /DONE \(1024 \+ 1023 entries\)$/);
		for (const table of [MAIN, BW]) {
			const written = fs.readFileSync(outFile(root, table.file), 'utf8');
			assert.equal(fs.readFileSync(cacheFile(root, table.file), 'utf8'), written);
			assert.deepEqual(plain(evaluate(written)[table.name]), plain(evaluate(fullSize(table.text))[table.name]));
		}
		assert.deepEqual(fs.readdirSync(path.dirname(outFile(root, MAIN.file))).sort(), [BW.file, MAIN.file]);
	});

	it('restores the last good copy when the fetch fails', async () => {
		const root = tempRoot('sprites.example.test');
		await run(root, serve({ [MAIN.file]: fullSize(UPSTREAM_MAIN), [BW.file]: fullSize(UPSTREAM_BW) }).fetchImpl);
		const good = [MAIN, BW].map(table => fs.readFileSync(outFile(root, table.file), 'utf8'));
		for (const table of [MAIN, BW]) fs.unlinkSync(outFile(root, table.file));

		const offline = new TypeError('fetch failed', { cause: new Error('getaddrinfo ENOTFOUND sprites.example.test') });
		const { result, line } = await run(root, () => Promise.reject(offline));
		assert.equal(result.status, 'restored');
		assert.match(line, /FAILED \(fetch failed: getaddrinfo ENOTFOUND sprites\.example\.test\); restored the last good copy from caches\/phnn-minidex$/);
		assert.deepEqual([MAIN, BW].map(table => fs.readFileSync(outFile(root, table.file), 'utf8')), good);
	});

	it('keeps the pair together when only one table fails validation', async () => {
		const root = tempRoot('sprites.example.test');
		await run(root, serve({ [MAIN.file]: fullSize(UPSTREAM_MAIN), [BW.file]: fullSize(UPSTREAM_BW) }).fetchImpl);
		const good = [MAIN, BW].map(table => fs.readFileSync(outFile(root, table.file), 'utf8'));

		const fresh = serve({ [MAIN.file]: fullSize(UPSTREAM_MAIN, 1), [BW.file]: '<html><body>502 Bad Gateway</body></html>' });
		const { result, line } = await run(root, fresh.fetchImpl);
		assert.equal(result.status, 'restored');
		assert.match(line, /FAILED \(pokedex-mini-bw\.js: expected 'exports\.BattlePokemonSpritesBW =' at line 1\)/);
		assert.deepEqual([MAIN, BW].map(table => fs.readFileSync(outFile(root, table.file), 'utf8')), good);
	});

	it('rejects a well-formed table that is too small', async () => {
		const root = tempRoot('sprites.example.test');
		const { result, line } = await run(root, serve({ [MAIN.file]: UPSTREAM_MAIN, [BW.file]: fullSize(UPSTREAM_BW) }).fetchImpl);
		assert.equal(result.status, 'missing');
		assert.match(line, /FAILED \(pokedex-mini\.js has only 24 entries\); there is no last good copy in caches\/phnn-minidex yet, so battles show static sprites$/);
		assert.equal(fs.existsSync(outFile(root, MAIN.file)), false);
	});

	it('does not restore a tampered last good copy', async () => {
		const root = tempRoot('sprites.example.test');
		await run(root, serve({ [MAIN.file]: fullSize(UPSTREAM_MAIN), [BW.file]: fullSize(UPSTREAM_BW) }).fetchImpl);
		for (const table of [MAIN, BW]) fs.unlinkSync(outFile(root, table.file));
		fs.appendFileSync(cacheFile(root, MAIN.file), 'alert(1);\n');

		const { result, line } = await run(root, () => Promise.reject(new Error('offline')));
		assert.equal(result.status, 'missing');
		assert.match(line, /the last good copy is unusable \(pokedex-mini\.js: unexpected text after the table at line \d+\)/);
		for (const table of [MAIN, BW]) assert.equal(fs.existsSync(outFile(root, table.file)), false);
	});

	it('writes a restored copy from the parsed data, never the cached bytes', async () => {
		for (const sep of ['\r', '\u2028', '\u2029']) {
			const root = tempRoot('sprites.example.test');
			await run(root, serve({ [MAIN.file]: fullSize(UPSTREAM_MAIN), [BW.file]: fullSize(UPSTREAM_BW) }).fetchImpl);
			const good = [MAIN, BW].map(table => fs.readFileSync(outFile(root, table.file), 'utf8'));
			for (const table of [MAIN, BW]) fs.unlinkSync(outFile(root, table.file));
			const cached = fs.readFileSync(cacheFile(root, MAIN.file), 'utf8');
			fs.writeFileSync(cacheFile(root, MAIN.file), `// note${sep}globalThis.pwned = 1; //\n` + cached);

			const { result } = await run(root, () => Promise.reject(new Error('offline')));
			assert.equal(result.status, 'missing', JSON.stringify(sep));
			for (const table of [MAIN, BW]) assert.equal(fs.existsSync(outFile(root, table.file)), false);

			fs.writeFileSync(cacheFile(root, MAIN.file), '/* note */\n' + cached);
			assert.equal((await run(root, () => Promise.reject(new Error('offline')))).result.status, 'restored');
			assert.deepEqual([MAIN, BW].map(table => fs.readFileSync(outFile(root, table.file), 'utf8')), good);
		}
	});

	it('stops reading a response as soon as it passes the size cap', async () => {
		const realFetch = globalThis.fetch;
		let sent = 0;
		const chunk = new Uint8Array(64 * 1024).fill(0x20);
		globalThis.fetch = async () => new Response(new ReadableStream({
			pull(controller) {
				sent += chunk.byteLength;
				controller.enqueue(chunk);
			},
		}), { status: 200 });
		try {
			await assert.rejects(fetchText('https://sprites.example.test/data/pokedex-mini.js'), /is too large/);
		} finally {
			globalThis.fetch = realFetch;
		}
		assert.ok(sent < 5 * 1024 * 1024, `read ${sent} bytes`);
	});

	it('never throws, even with no last good copy and an odd failure', async () => {
		const root = tempRoot();
		const { result, line } = await run(root, () => {
			throw 'socket hang up';
		});
		assert.equal(result.status, 'missing');
		assert.match(line, /^Using upstream's animated sprite dimensions from https:\/\/play\.pokemonshowdown\.com\/data\/\.\.\. FAILED \(socket hang up\); there is no last good copy in caches\/phnn-minidex yet/);
		assert.equal(fs.existsSync(outFile(root, MAIN.file)), false);
	});

	it('runs from build-minidex when it skips, into ignored paths', () => {
		const buildMinidex = fs.readFileSync(path.join(repoRoot, 'build-tools/build-minidex'), 'utf8');
		assert.match(buildMinidex, /console\.log\('SKIPPED'\);\n\tawait \(await import\('\.\/phnn-minidex\.js'\)\)\.default\.updateMinidex\(\);\n\}/);
		const gitignore = fs.readFileSync(path.join(repoRoot, '.gitignore'), 'utf8').split('\n');
		assert.ok(gitignore.includes('/play.pokemonshowdown.com/data/'));
		assert.ok(gitignore.includes('/caches/'));
	});
});
